"""Start Athena automatically when Windows logs in.

Uses the per-user Startup folder rather than the registry or Task Scheduler:
no admin rights needed, and you can see and delete exactly one file if you
ever want it gone.

The launcher it writes is a .vbs because that is the only way on Windows to
start a process with no console window flashing up at login.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

from .config import ROOT, cfg

LAUNCHER_NAME = "Athena.vbs"


def startup_dir() -> Path:
    return Path(os.environ["APPDATA"]) / "Microsoft" / "Windows" / "Start Menu" / "Programs" / "Startup"


def launcher_path() -> Path:
    return startup_dir() / LAUNCHER_NAME


def _pythonw() -> Path:
    """The windowed interpreter, so nothing flashes a console at login."""
    pw = Path(sys.executable).with_name("pythonw.exe")
    return pw if pw.exists() else Path(sys.executable)


def _script(modes: list[str], delay: int) -> str:
    pyw = _pythonw()

    lines = [
        "' Athena autostart - generated by: python run.py autostart on",
        "' Delete this file, or run: python run.py autostart off",
        "Set sh = CreateObject(\"WScript.Shell\")",
        f'sh.CurrentDirectory = "{ROOT}"',
        "",
        "' Give Windows a moment to finish logging in and bring up networking",
        f"WScript.Sleep {delay * 1000}",
        "",
    ]
    # The HUD window starts the web server itself when it finds none, so
    # launched alongside web it could race it for port 8420. It goes last,
    # after the server has had a few seconds to come up.
    modes = [m for m in modes if m != "gui"] + (["gui"] if "gui" in modes else [])
    for mode in modes:
        if mode == "gui" and len(modes) > 1:
            lines.append("WScript.Sleep 8000")
        # Straight through pythonw, which writes its own data/<mode>.log. The
        # old hidden `cmd /c ... > log` wrapper could be closed by Windows
        # as a hung window, killing the process inside it.
        lines.append(f'sh.Run """{pyw}"" run.py {mode}", 0, False')
    return "\r\n".join(lines) + "\r\n"


def enable(modes: list[str] | None = None, delay: int | None = None) -> str:
    modes = modes or cfg.get("autostart.modes", ["hotkey"])
    delay = delay if delay is not None else int(cfg.get("autostart.delay_seconds", 20))

    valid = {"hotkey", "voice", "gui", "web"}
    bad = [m for m in modes if m not in valid]
    if bad:
        return f"ERROR: unknown mode(s) {bad}. Choose from: hotkey, voice, gui, web."

    path = launcher_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(_script(modes, delay), encoding="utf-8")
    return (f"Autostart enabled for: {', '.join(modes)}\n"
            f"Launcher: {path}\n"
            f"It waits {delay}s after login before starting.")


def disable() -> str:
    path = launcher_path()
    if not path.exists():
        return "Autostart was not enabled."
    path.unlink()
    return f"Autostart disabled. Removed {path}"


def status() -> str:
    path = launcher_path()
    if not path.exists():
        return "Autostart: off\nTurn it on with: python run.py autostart on"
    body = path.read_text(encoding="utf-8", errors="replace")
    modes = []
    for mode in ("hotkey", "voice", "gui", "web"):
        if f"run.py {mode}" in body:
            modes.append(mode)
    return (f"Autostart: on ({', '.join(modes) or 'unknown'})\n"
            f"Launcher: {path}")
